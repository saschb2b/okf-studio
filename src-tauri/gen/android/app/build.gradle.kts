// Release signing. An unsigned release APK cannot be installed at all, so the
// APK attached to a GitHub release is signed with the shared debug key checked
// in beside this file. That key's password is public, so the signature proves
// nothing about who built the APK. What it does buy is that every release is
// signed with the *same* key, and Android only installs an update whose
// signature matches the installed app.
//
// To sign with a real key instead, drop a keystore.properties next to
// gradlew (storeFile, storePassword, keyAlias, keyPassword). It is picked up
// with no edit here and is git-ignored. Changing the key means users have to
// uninstall first, so make that switch before any store listing rather than
// after. See docs/architecture/build-and-release.md.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

